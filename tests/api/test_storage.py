# A tiny valid 1x1 PNG, so real image bytes flow through save()/read() rather
# than an arbitrary blob that happens to pass content-type checks alone.
PNG_1PX = bytes.fromhex(
    "89504e470d0a1a0a0000000d494844440000000100000001080600000"
    "01f15c4890000000a49444154789c6360000002000155e28f760000000049454e44ae426082"
)


def _user(session, email: str, role: Role = Role.participant) -> User:
    user = User(email=email, name=email.split("@")[0], role=role, password_hash=hash_password("supersecret1"))
    session.add(user)
    session.commit()
    session.refresh(user)
    return user


def _login_as(client, session, email: str) -> None:
    client.post("/api/auth/logout")
    client.post("/api/auth/login", json={"email": email, "password": "supersecret1"})


def _event(session, slug: str) -> Event:
    owner = _user(session, f"{slug}-owner@example.com", Role.organizer)
    event = Event(
        slug=slug, name="Storage Event",
        start_at=utcnow() - timedelta(days=1), end_at=utcnow() + timedelta(days=1),
        created_by_id=owner.id,
    )
    session.add(event)
    session.commit()
    session.refresh(event)
    return event


def _team_with_submission(session, event: Event, member_email: str, name: str) -> tuple[Team, Submission]:
    member = _user(session, member_email)
    team = Team(event_id=event.id, name=name)
    session.add(team)
    session.commit()
    session.refresh(team)
    session.add(TeamMembership(team_id=team.id, user_id=member.id))
    submission = Submission(team_id=team.id, event_id=event.id, title="Widget", description="d",
                             status=SubmissionStatus.submitted)
    session.add(submission)
    session.commit()
    session.refresh(submission)
    return team, submission


