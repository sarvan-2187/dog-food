def test_a_team_member_can_upload_their_submissions_image(client, session):
    event = _event(session, "storage-upload")
    team, submission = _team_with_submission(session, event, "upload-member@example.com", "Team Upload")
    _login_as(client, session, "upload-member@example.com")

    r = client.post(
        f"/api/teams/{team.id}/submission/image",
        files={"file": ("shot.png", PNG_1PX, "image/png")},
    )
    assert r.status_code == 200, r.text
    image_url = r.json()["image_url"]
    assert image_url.startswith("/media/")

    served = client.get(image_url)
    assert served.status_code == 200
    assert served.headers["content-type"] == "image/png"
    assert served.content == PNG_1PX


def test_uploading_again_replaces_the_old_image_rather_than_orphaning_it(client, session):
    event = _event(session, "storage-replace")
    team, _submission = _team_with_submission(session, event, "replace-member@example.com", "Team Replace")
    _login_as(client, session, "replace-member@example.com")

    first = client.post(
        f"/api/teams/{team.id}/submission/image", files={"file": ("a.png", PNG_1PX, "image/png")}
    ).json()["image_url"]
    second = client.post(
        f"/api/teams/{team.id}/submission/image", files={"file": ("b.png", PNG_1PX, "image/png")}
    ).json()["image_url"]

    assert first != second
    # The old key is gone, not merely unreferenced -- it 404s, it doesn't still serve.
    assert client.get(first).status_code == 404
    assert client.get(second).status_code == 200


def test_a_non_member_cannot_upload_to_someone_elses_submission(client, session):
    event = _event(session, "storage-cross-team")
    team, _submission = _team_with_submission(session, event, "owner-member@example.com", "Team Owner")
    _user(session, "outsider@example.com")
    _login_as(client, session, "outsider@example.com")

    r = client.post(
        f"/api/teams/{team.id}/submission/image", files={"file": ("shot.png", PNG_1PX, "image/png")}
    )
    assert r.status_code == 403


def test_upload_rejects_a_disallowed_content_type_with_a_plain_message(client, session):
    event = _event(session, "storage-bad-type")
    team, _submission = _team_with_submission(session, event, "badtype-member@example.com", "Team Bad Type")
    _login_as(client, session, "badtype-member@example.com")

    r = client.post(
        f"/api/teams/{team.id}/submission/image",
        files={"file": ("doc.pdf", b"%PDF-1.4", "application/pdf")},
    )
    assert r.status_code == 422
    assert "Unsupported image type" in r.json()["detail"]


def test_avatar_upload_is_self_only_and_shows_up_on_me(client, session):
    _user(session, "avatar-user@example.com")
    _login_as(client, session, "avatar-user@example.com")

    before = client.get("/api/auth/me").json()
    assert before["avatar_url"] is None

    r = client.post("/api/users/me/avatar", files={"file": ("me.png", PNG_1PX, "image/png")})
    assert r.status_code == 200, r.text

    after = client.get("/api/auth/me").json()
    assert after["avatar_url"] == r.json()["avatar_url"]


def test_serving_an_unknown_key_404s_in_plain_language(client):
    r = client.get("/media/does-not-exist.png")
    assert r.status_code == 404
