def test_local_storage_saves_and_reads_back_bytes(tmp_path):
    storage = LocalStorage(tmp_path)
    key = storage.save(PNG_1PX, "image/png")
    assert storage.exists(key)
    assert storage.read(key) == PNG_1PX


def test_local_storage_rejects_an_unsupported_content_type(tmp_path):
    storage = LocalStorage(tmp_path)
    with pytest.raises(StorageError, match="Unsupported image type"):
        storage.save(PNG_1PX, "application/pdf")


def test_local_storage_rejects_an_oversized_file(tmp_path):
    storage = LocalStorage(tmp_path)
    too_big = b"\x00" * (5 * 1024 * 1024 + 1)
    with pytest.raises(StorageError, match="must be under"):
        storage.save(too_big, "image/png")


def test_local_storage_cannot_be_made_to_write_outside_its_root(tmp_path):
    """A key is always generated by save() itself, never accepted from a
    caller -- this proves _resolve() would refuse one even if some future bug
    ever let a crafted key reach it."""
    storage = LocalStorage(tmp_path)
    with pytest.raises(StorageError, match="Invalid file key"):
        storage._resolve("../../etc/passwd")
    with pytest.raises(StorageError, match="Invalid file key"):
        storage._resolve("../outside.png")


